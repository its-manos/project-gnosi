/* Lesson 17 — standalone Node-only structural/compatibility assertions; not a native test. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts');
const {inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const progress=require(root+'/src/utils/lessonProgress.ts');
const paths=require(root+'/src/utils/lessonPath.ts');
const {quizFingerprint,lessonQuizMatches}=require(root+'/src/utils/learningActivity.ts');
const {parseLearningBackup}=require(root+'/src/utils/learningBackup.ts');
const {lessonReview}=require(root+'/src/utils/lessonReview.ts');
const lesson=lessons.find(x=>x.id==='greek-war-hoplites');
assert.ok(lesson,'Lesson 17 must be live');
assert.equal(lessons.filter(x=>x.id===lesson.id).length,1);
assert.equal(lesson.title,'Πίσω από την ασπίδα: οι οπλίτες των ελληνικών πόλεων');
assert.equal(lesson.requireCurrentAttemptQuiz,true);
assert.equal(lesson.compatibleQuizKeys,undefined);
assert.equal(lesson.sections.length,6);
const paragraphs=lesson.sections.flatMap(s=>s.paragraphs);
assert.equal(paragraphs.length,24);
assert.deepEqual(paragraphs.map(x=>x.id),Array.from({length:24},(_,i)=>'hoplite-'+String(i+1).padStart(2,'0')));
assert.equal(lesson.questions.length,6);
assert.deepEqual(lesson.checkpoints.map(c=>c.questionId),lesson.questions.map(q=>q.id));
assert.deepEqual(progress.getQuestionPlacements(lesson).map(p=>p.afterParagraphNumber),[4,8,12,16,20,24]);
assert.equal(progress.getVisibleParagraphLimit(lesson,{}),4);
assert.equal(progress.getResumeParagraphNumber(lesson,{0:lesson.questions[0].correctIndex}),5);
assert.equal(progress.getVisibleParagraphLimit(lesson,Object.fromEntries(lesson.questions.map((q,i)=>[i,q.correctIndex]))),24);
assert.ok(lesson.questions.every(q=>q.version==='1'&&q.answers.length===4&&new Set(q.answers).size===4&&q.correctIndex>=0&&q.correctIndex<4&&q.explanation.length>70));
assert.equal(new Set(lesson.questions.map(q=>q.id)).size,6);
assert.ok(lesson.sources.length>=12&&lesson.sources.every(s=>s.url.startsWith('https://')));
assert.ok(lesson.imageCredit.includes('CC BY-SA 4.0')&&lesson.imageUrl.includes('Special:FilePath/'));
assert.equal(lesson.imageResizeMode,'contain');
const images=inlineArticleMedia[lesson.id];
assert.equal(images.length,2);
assert.deepEqual(images.map(x=>x.afterParagraphId),['hoplite-07','hoplite-10']);
assert.ok(images.every(x=>x.resizeMode==='contain'&&x.creditUrl.startsWith('https://commons.wikimedia.org/wiki/File:')&&x.url.includes('Special:FilePath/')));
const seq=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.deepEqual(seq.slice(14,21).map(x=>x.id),['athens-who-voted','athens-law-courts','greek-war-hoplites','greek-sanctuaries-games','persian-wars-greek-world','athenian-empire','antikythera-gears']);
assert.equal(paths.getLessonAccess(lesson,lessons,[]).unlocked,false);
assert.equal(paths.getLessonAccess(lesson,lessons,['athens-law-courts']).unlocked,true);
assert.equal(paths.getLessonAccess(lesson,lessons,[lesson.id]).unlocked,true);
const key=quizFingerprint(lesson.questions);
assert.ok(key.startsWith('q_'));
assert.ok(!lessonQuizMatches(lesson,'q_470dac57')&&!lessonQuizMatches(lesson,'q_22487292'));
const legacy={historic:{lessonId:'athens-who-voted',at:Date.parse('2026-10-20T12:00Z'),wasCompleted:true,questionCount:4,correctCount:3,quizKey:'q_470dac57',missedQuestionIndices:[1]}};
assert.equal(lessonReview(lesson,legacy).status,'no-result');
assert.equal(lessonReview(lessons.find(x=>x.id==='athens-who-voted'),legacy).status,'changed');
const attempt={checkpointAnswers:{0:lesson.questions[0].correctIndex},quizKey:key,score:1,updatedAt:Date.now(),replayOfCompletedLesson:false};
let saved=parseLearningBackup({schemaVersion:1,completedIds:['athens-law-courts','athens-who-voted'],savedIds:['athens-who-voted',lesson.id],attempts:{[lesson.id]:attempt}});
assert.equal(saved.attempts[lesson.id].quizKey,key);
assert.ok(saved.completedIds.includes('athens-law-courts')&&saved.savedIds.includes('athens-who-voted'));
saved=parseLearningBackup({schemaVersion:1,completedIds:['athens-law-courts','athens-who-voted'],savedIds:[lesson.id],attempts:{[lesson.id]:{...attempt,quizKey:'q_other'}}});
assert.ok(!saved.attempts[lesson.id]&&saved.savedIds.includes(lesson.id));
console.log('Hoplite Lesson 17 structural, checkpoint, media, access, and historical quiz isolation checks passed (Node only).');
