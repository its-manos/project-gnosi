/* Lesson 21: focused structural and old-progress isolation checks. Node/native execution must be reported separately. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts'),{inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const progress=require(root+'/src/utils/lessonProgress.ts'),paths=require(root+'/src/utils/lessonPath.ts');
const {quizFingerprint,lessonQuizMatches}=require(root+'/src/utils/learningActivity.ts');
const {parseLearningBackup}=require(root+'/src/utils/learningBackup.ts');
const id='peloponnesian-war',l=lessons.find(x=>x.id===id);
assert.ok(l);assert.equal(lessons.filter(x=>x.id===id).length,1);
assert.equal(l.title,"Πελοποννησιακός Πόλεμος: φόβος, επιλογές και εξάντληση");assert.equal(l.requireCurrentAttemptQuiz,true);
assert.equal(l.compatibleQuizKeys,undefined);assert.equal(l.sections.length,7);
const ps=l.sections.flatMap(s=>s.paragraphs);assert.equal(ps.length,35);
assert.deepEqual(ps.map(p=>p.id),Array.from({length:35},(_,i)=>'war-'+String(i+1).padStart(2,'0')));
assert.equal(l.questions.length,7);assert.equal(new Set(l.questions.map(q=>q.id)).size,7);
assert.ok(l.questions.every(q=>q.version==='1'&&q.difficulty==='hard'&&q.answers.length===4&&new Set(q.answers).size===4&&q.explanation.length>70));
assert.deepEqual(l.checkpoints.map(c=>c.questionId),l.questions.map(q=>q.id));
assert.deepEqual(progress.getQuestionPlacements(l).map(p=>p.afterParagraphNumber),[4,9,14,19,24,29,35]);
assert.equal(progress.getVisibleParagraphLimit(l,{}),4);
assert.equal(progress.getResumeParagraphNumber(l,{0:l.questions[0].correctIndex}),5);
assert.equal(progress.getVisibleParagraphLimit(l,Object.fromEntries(l.questions.map((q,i)=>[i,q.correctIndex]))),35);
assert.deepEqual(inlineArticleMedia[id].map(m=>m.afterParagraphId),['war-12','war-23']);
assert.ok(inlineArticleMedia[id].every(m=>m.resizeMode==='contain'&&/Special:FilePath/.test(m.url)&&m.creditUrl.includes('commons.wikimedia.org/wiki/File:')));
const seq=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.deepEqual(seq.slice(19,22).map(x=>x.id),['athenian-empire',id,'antikythera-gears']);
assert.ok(paths.getLessonAccess(l,lessons,['athenian-empire']).unlocked);
assert.ok(!paths.getLessonAccess(l,lessons,['persian-wars-greek-world']).unlocked);
assert.equal(paths.getNextPathLesson(lessons.find(x=>x.id==='athenian-empire'),lessons,['athenian-empire'])?.id,id);
for(const old of ['q_470dac57','q_22487292',...['athenian-empire','persian-wars-greek-world'].map(x=>quizFingerprint(lessons.find(t=>t.id===x).questions))]) assert.ok(!lessonQuizMatches(l,old));
const saved=parseLearningBackup({schemaVersion:1,completedIds:['athens-who-voted','athenian-empire'],savedIds:[id,'athens-who-voted'],attempts:{}});
assert.ok(saved.completedIds.includes('athens-who-voted')&&saved.savedIds.includes(id));
console.log('Peloponnesian War dedicated structural, path and history-isolation assertions passed (Node only).');
