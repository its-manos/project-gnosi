/* Lesson 13 integration contract. Run locally with Node and installed TypeScript. */
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict'), ts = require('typescript');
require.extensions['.ts'] = (m,f) => m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'), { compilerOptions: { module:ts.ModuleKind.CommonJS, target:ts.ScriptTarget.ES2020, esModuleInterop:true } }).outputText, f);
const root=path.resolve(__dirname,'..');
const { lessons }=require(root+'/src/data/lessons.ts');
const { inlineArticleMedia }=require(root+'/src/data/articleMedia.ts');
const progress=require(root+'/src/utils/lessonProgress.ts');
const pathUtils=require(root+'/src/utils/lessonPath.ts');
const l=lessons.find(x=>x.id==='greek-settlements-networks');
assert.ok(l,'Lesson 13 must exist');
assert.equal(lessons.filter(x=>x.id===l.id).length,1);
assert.equal(l.requireCurrentAttemptQuiz,true);
assert.equal(l.compatibleQuizKeys,undefined,'no legacy quiz alias for a new article');
assert.equal(l.sections.length,5);
const paragraphs=l.sections.flatMap(s=>s.paragraphs);
assert.equal(paragraphs.length,25);
assert.deepEqual(paragraphs.map(x=>x.id), Array.from({length:25},(_,i)=>'settle-'+String(i+1).padStart(2,'0')));
assert.equal(l.questions.length,5);
assert.deepEqual(l.checkpoints.map(x=>x.questionId),l.questions.map(x=>x.id));
assert.deepEqual(progress.getQuestionPlacements(l).map(x=>x.afterParagraphNumber),[5,10,15,20,25]);
assert.equal(new Set(l.questions.map(x=>x.id)).size,5);
assert.ok(l.questions.every(q=>q.version==='1'&&q.answers.length===4&&q.correctIndex>=0&&q.correctIndex<4&&q.explanation.length>=50));
assert.ok(l.sources.length>=8 && l.sources.every(s=>s.url.startsWith('https://')));
assert.ok(l.imageCreditUrl.includes('commons.wikimedia.org/wiki/File:'));
assert.ok(l.imageUrl.includes('Special:FilePath/') && l.imageUrl.includes('width=1200'));
assert.deepEqual(inlineArticleMedia[l.id].map(x=>x.afterParagraphId),['settle-09','settle-18']);
assert.ok(inlineArticleMedia[l.id].every(x=>x.resizeMode==='contain'&&x.creditUrl.includes('commons.wikimedia.org/wiki/File:')&&x.url.includes('width=1200')));
const sequence=pathUtils.getSubcategoryPath(lessons,'ancient-greece');
assert.equal(sequence[10].id,'geometric-greece');
assert.equal(sequence[11].id,'rise-of-polis');
assert.equal(sequence[12].id,l.id);
assert.equal(sequence[13].id,'sparta-society');assert.equal(sequence[14].id,'athens-who-voted');
assert.equal(pathUtils.getLessonAccess(l,lessons,[]).unlocked,false);
assert.equal(pathUtils.getLessonAccess(l,lessons,['rise-of-polis']).unlocked,true);
assert.equal(pathUtils.getLessonAccess(l,lessons,[l.id]).unlocked,true);
assert.equal(pathUtils.getLessonAccess(sequence[11],lessons,['geometric-greece']).unlocked,true);
console.log('Greek settlement networks structural, anchored quiz, media and path checks passed (Node only).');
