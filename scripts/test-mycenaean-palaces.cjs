/* Structural and progress-policy QA only; no device, network, native audio or image HTTP checks. */
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..'),{lessons}=require(root+'/src/data/lessons.ts'),progress=require(root+'/src/utils/lessonProgress.ts'),paths=require(root+'/src/utils/lessonPath.ts');
const {inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const lesson=lessons.find(l=>l.id==='mycenaean-palaces');
assert.ok(lesson?.requireCurrentAttemptQuiz);
const paras=lesson.sections.flatMap(s=>s.paragraphs);
assert.equal(paras.length,25);assert.equal(new Set(paras.map(p=>p.id)).size,25);
assert.deepEqual(progress.getQuestionPlacements(lesson).map(p=>p.afterParagraphNumber),[4,10,15,20,24]);
assert.deepEqual(lesson.checkpoints.map(c=>c.questionId),lesson.questions.map(q=>q.id));
assert.deepEqual(inlineArticleMedia[lesson.id].map(m=>m.afterParagraphId),['hides-tablet','tiryns-gate']);
assert.deepEqual(lesson.questions.map(q=>q.correctIndex),[0,2,3,1,2]);
assert.ok(lesson.questions.every(q=>q.version==='1'&&q.answers.length===4&&new Set(q.answers).size===4&&q.explanation.length>35));
const a=lesson.questions.map(q=>q.correctIndex);
assert.equal(progress.getVisibleParagraphLimit(lesson,{}),4);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a[0]}),10);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a[0],1:a[1]}),15);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a[0],1:a[1],2:a[2]}),20);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a[0],1:a[1],2:a[2],3:a[3]}),24);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a[0],1:a[1],2:a[2],3:a[3],4:a[4]}),25);
assert.equal(progress.getResumeParagraphNumber(lesson,{0:a[0],1:a[1]}),11);
const ordered=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.equal(ordered.findIndex(l=>l.id===lesson.id),7);
assert.ok(!paths.getLessonAccess(lesson,lessons,[]).unlocked);
assert.ok(paths.getLessonAccess(lesson,lessons,['minoan-crete']).unlocked);
assert.ok(paths.getLessonAccess(lesson,lessons,[lesson.id]).unlocked);
assert.ok(paths.getLessonAccess(lesson,lessons,[],[lesson.id]).unlocked);
console.log('Mycenaean palaces: paragraph/checkpoint/media/order/access structural assertions passed (Node only).');
