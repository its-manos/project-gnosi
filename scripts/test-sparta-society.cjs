/* Lesson 14 structural, checkpoint, media and backward-compatible path contract. Run with npm-installed TypeScript. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts');
const {inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const progress=require(root+'/src/utils/lessonProgress.ts');
const paths=require(root+'/src/utils/lessonPath.ts');
const l=lessons.find(x=>x.id==='sparta-society');
assert.ok(l);assert.equal(lessons.filter(x=>x.id===l.id).length,1);
assert.equal(l.requireCurrentAttemptQuiz,true);assert.equal(l.compatibleQuizKeys,undefined);
assert.equal(l.sections.length,6);
const paras=l.sections.flatMap(s=>s.paragraphs);assert.equal(paras.length,26);
assert.deepEqual(paras.map(p=>p.id),Array.from({length:26},(_,i)=>'sparta-'+String(i+1).padStart(2,'0')));
assert.equal(l.questions.length,6);
assert.deepEqual(l.checkpoints.map(c=>c.questionId),l.questions.map(q=>q.id));
assert.deepEqual(progress.getQuestionPlacements(l).map(p=>p.afterParagraphNumber),[4,9,13,17,22,26]);
assert.ok(l.questions.every(q=>q.version==='1'&&q.answers.length===4&&new Set(q.answers).size===4&&q.correctIndex>=0&&q.correctIndex<=3&&q.explanation.length>=65));
assert.equal(new Set(l.questions.map(q=>q.id)).size,6);
assert.ok(l.sources.length>=11&&l.sources.every(s=>s.url.startsWith('https://')));
const art=inlineArticleMedia[l.id];assert.equal(art.length,2);
assert.deepEqual(art.map(x=>x.afterParagraphId),['sparta-23','sparta-24']);
assert.ok(art.every(x=>x.resizeMode==='contain'&&x.creditUrl.startsWith('https://commons.wikimedia.org/wiki/File:')&&x.url.includes('Special:FilePath/')));
assert.ok(l.imageUrl.includes('Special:FilePath/')&&l.imageCreditUrl.includes('commons.wikimedia.org/wiki/File:'));
const seq=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.deepEqual(seq.slice(11,15).map(x=>x.id),['rise-of-polis','greek-settlements-networks','sparta-society','athens-who-voted']);
assert.equal(paths.getLessonAccess(l,lessons,[]).unlocked,false);
assert.equal(paths.getLessonAccess(l,lessons,['greek-settlements-networks']).unlocked,true);
assert.equal(paths.getLessonAccess(l,lessons,[l.id]).unlocked,true);
assert.equal(paths.getLessonAccess(seq[14],lessons,['greek-settlements-networks']).unlocked,false,'existing Athens draft must remain gated behind Sparta');
assert.equal(paths.getLessonAccess(seq[14],lessons,['sparta-society']).unlocked,true);
assert.equal(paths.getLessonAccess(seq[14],lessons,['athens-who-voted']).unlocked,true,'historical completed lesson remains accessible');
console.log('Sparta social lesson structural, checkpoint, image and access checks passed (Node only).');
