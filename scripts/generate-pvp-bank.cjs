/* global __dirname */
// Historical seed is immutable. New content and selectors go in a new release migration.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { load } = require('./helpers/load-typescript.cjs');
const { quickQuizQuestions } = load('src/data/quickQuizQuestions.ts');
const { createQuizSession, evaluateAnswer } = load('src/quiz/engine.ts');
for (let i = 0; i < quickQuizQuestions.length; i += 10) createQuizSession(`pvp-bank:${i}`, 'challenge', quickQuizQuestions.slice(i, i + 10));
for (const question of quickQuizQuestions) {
  assert.ok(question.content.answers.length === 4 && evaluateAnswer(question, question.content.correctIndex).correct, question.id);
}
const migrations = path.join(__dirname, '../supabase/migrations');
const baseline = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures/play-banks-before-v2.json'), 'utf8')).quick;
const rows = bank => bank.map(q => `('${q.id.replaceAll("'", "''")}', $pvpbank$${JSON.stringify(q)}$pvpbank$::jsonb)`).join(',\n');
const legacy = `-- Frozen from the shared Quick Quiz bank. Generated by scripts/generate-pvp-bank.cjs.\n-- Apply after 202611120016_friends_pvp.sql. Do not regenerate an applied migration.\nbegin;\ninsert into public.pvp_questions(id,question) values\n${rows(baseline)}\non conflict(id) do update set question=excluded.question;\ncommit;\n`;
assert.equal(fs.readFileSync(path.join(migrations, '202611120017_friends_pvp_bank.sql'), 'utf8'), legacy, 'Historical seed changed');
const files = fs.readdirSync(migrations).filter(f => f.endsWith('_quiz_bank_v2.sql'));
assert.equal(files.length, 1, 'Create a release migration with supabase migration new quiz_bank_v2');
const old = new Map(baseline.map(q => [q.id, q]));
for (const [id, q] of old) assert.equal(JSON.stringify(quickQuizQuestions.find(x => x.id === id)), JSON.stringify(q), `Published question changed: ${id}`);
const added = quickQuizQuestions.filter(q => !old.has(q.id));
const functions = fs.readFileSync(path.join(__dirname, '../content/quiz/pvp-v2-functions.sql'), 'utf8');
const sql = `-- Quiz v2: append-only content, eight categories, balanced matches.\n-- Generated by scripts/generate-pvp-bank.cjs. Freeze after release.\nbegin;\ninsert into public.pvp_questions(id,question) values\n${rows(added)}\non conflict(id) do nothing;\n${functions}\ncommit;\n`;
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(path.join(migrations, files[0]), 'utf8'), sql, 'Regenerate the unreleased v2 migration');
else fs.writeFileSync(path.join(migrations, files[0]), sql);
console.log(`PvP bank: ${baseline.length} frozen + ${added.length} additions; ${quickQuizQuestions.length} validated questions.`);
