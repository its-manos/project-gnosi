/* global __dirname */
// Freeze shared authored content into a server migration; live matches keep their
// own snapshots. After release, publish content changes in a NEW migration.
const fs = require('node:fs');
const path = require('node:path');
const { load } = require('./helpers/load-typescript.cjs');
const { quickQuizQuestions } = load('src/data/quickQuizQuestions.ts');
const { createQuizSession, evaluateAnswer } = load('src/quiz/engine.ts');
createQuizSession('pvp-bank-validation', 'challenge', quickQuizQuestions);
for (const question of quickQuizQuestions) {
  if (question.content.answers.length !== 4 || !evaluateAnswer(question, question.content.correctIndex).correct) throw Error(question.id);
}
const rows = quickQuizQuestions.map(question => `('${question.id.replaceAll("'", "''")}', $pvpbank$${JSON.stringify(question)}$pvpbank$::jsonb)`).join(',\n');
const sql = `-- Frozen from the shared Quick Quiz bank. Generated by scripts/generate-pvp-bank.cjs.\n-- Apply after 202611120016_friends_pvp.sql. Do not regenerate an applied migration.\nbegin;\ninsert into public.pvp_questions(id,question) values\n${rows}\non conflict(id) do update set question=excluded.question;\ncommit;\n`;
const file = path.join(__dirname, '../supabase/migrations/202611120017_friends_pvp_bank.sql');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== sql) throw Error('PvP seed differs from the shared bank. Add a new content migration after release.');
} else fs.writeFileSync(file, sql);
console.log(`PvP bank: ${quickQuizQuestions.length} shared, validated questions.`);
