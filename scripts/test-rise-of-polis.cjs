const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts');
const progress=require(root+'/src/utils/lessonProgress.ts');
const pathUtils=require(root+'/src/utils/lessonPath.ts');
const {inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const l=lessons.find(x=>x.id==='rise-of-polis');
assert.ok(l);assert.equal(lessons.filter(x=>x.id===l.id).length,1);
assert.equal(l.requireCurrentAttemptQuiz,true);
assert.equal(l.sections.flatMap(s=>s.paragraphs).length,23);
const ids=l.sections.flatMap(s=>s.paragraphs).map(p=>p.id);
assert.equal(new Set(ids).size,ids.length);
assert.deepEqual(progress.getQuestionPlacements(l).map(x=>x.afterParagraphNumber),[4,9,14,19,23]);
assert.deepEqual(l.checkpoints.map(x=>x.questionId),l.questions.map(x=>x.id));
assert.equal(new Set(l.questions.map(x=>x.id)).size,5);
assert.ok(l.questions.every(q=>q.version==='1'&&q.answers.length===4&&q.correctIndex>=0&&q.correctIndex<4&&!q.id.startsWith('q_')));
assert.equal(l.compatibleQuizKeys,undefined);
assert.deepEqual(inlineArticleMedia[l.id].map(x=>x.afterParagraphId),['polis-11']);
assert.ok(inlineArticleMedia[l.id].every(x=>x.creditUrl.includes('commons.wikimedia.org/wiki/File:')&&x.resizeMode==='contain'));
const seq=pathUtils.getSubcategoryPath(lessons,'ancient-greece');
assert.equal(seq[10].id,'geometric-greece');assert.equal(seq[11].id,l.id);assert.equal(seq[12].id,'athens-who-voted');
assert.equal(pathUtils.getLessonAccess(l,lessons,[]).unlocked,false);
assert.equal(pathUtils.getLessonAccess(l,lessons,['geometric-greece']).unlocked,true);
assert.equal(pathUtils.getLessonAccess(seq[10],lessons,['palace-collapse']).unlocked,true);
assert.equal(pathUtils.getLessonAccess(l,lessons,[l.id]).unlocked,true);
console.log('Rise of polis structural, checkpoint, media and access tests passed (Node only).');
