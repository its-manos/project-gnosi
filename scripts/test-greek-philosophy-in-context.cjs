/* Ancient Greece / Chapter V / Lesson 26 — Node-only contract, NOT device QA. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts'),{inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const p=require(root+'/src/utils/lessonProgress.ts'),paths=require(root+'/src/utils/lessonPath.ts');
const {quizFingerprint,lessonQuizMatches}=require(root+'/src/utils/learningActivity.ts');
const {parseLearningBackup}=require(root+'/src/utils/learningBackup.ts');
const id='greek-philosophy-in-context',l=lessons.find(x=>x.id===id);
assert.ok(l);assert.equal(lessons.filter(x=>x.id===id).length,1);
assert.equal(l.title,'Πού γινόταν η φιλοσοφία;'); 
assert.equal(l.categoryId,'history');assert.equal(l.subcategoryId,'ancient-greece');
assert.equal(l.requireCurrentAttemptQuiz,true);assert.equal(l.compatibleQuizKeys,undefined);
const ps=l.sections.flatMap(s=>s.paragraphs);
assert.equal(l.sections.length,6);assert.equal(ps.length,30);
assert.deepEqual(ps.map(x=>x.id),Array.from({length:30},(_,i)=>'phil-'+String(i+1).padStart(2,'0')));
assert.ok(ps.every(x=>x.text.length>=155));
assert.equal(l.questions.length,7);assert.equal(new Set(l.questions.map(q=>q.id)).size,7);
assert.ok(l.questions.every(q=>q.version==='1'&&q.difficulty==='hard'&&q.answers.length===4&&new Set(q.answers).size===4&&q.correctIndex>=0&&q.correctIndex<4&&q.explanation.length>=90));
assert.deepEqual(l.checkpoints.map(x=>x.questionId),l.questions.map(x=>x.id));
assert.deepEqual(p.getQuestionPlacements(l).map(x=>x.afterParagraphNumber),[4,8,12,16,20,25,30]);
assert.equal(p.getVisibleParagraphLimit(l,{}),4);
assert.equal(p.getResumeParagraphNumber(l,{0:l.questions[0].correctIndex}),5);
assert.equal(p.getVisibleParagraphLimit(l,Object.fromEntries(l.questions.map((q,i)=>[i,q.correctIndex]))),30);
assert.ok(l.sources.length>=12&&l.sources.every(s=>s.url.startsWith('https://')));
assert.ok(l.imageCreditUrl.includes('commons.wikimedia.org/wiki/File:'));
assert.deepEqual(inlineArticleMedia[id].map(x=>x.afterParagraphId),['phil-09','phil-21']);
assert.ok(inlineArticleMedia[id].every(x=>x.resizeMode==='contain'&&x.creditUrl.includes('/wiki/File:')&&x.caption.length>95));
const seq=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.deepEqual(seq.slice(23,28).map(x=>x.id),['alexander-conquests-context','greek-stage-tragedy',id,'antikythera-gears']);
assert.equal(paths.getNextPathLesson(lessons.find(x=>x.id==='greek-stage-tragedy'),lessons,['greek-stage-tragedy'])?.id,id);
assert.equal(paths.getNextPathLesson(l,lessons,[id])?.id,'greek-science-knowledge');
assert.ok(paths.getLessonAccess(l,lessons,['greek-stage-tragedy']).unlocked);
assert.ok(!paths.getLessonAccess(l,lessons,['alexander-conquests-context']).unlocked);
assert.ok(paths.getLessonAccess(l,lessons,[id]).unlocked);
const k=quizFingerprint(l.questions);assert.ok(k.startsWith('q_'));
for(const old of ['q_470dac57','q_22487292',...['greek-stage-tragedy','athens-who-voted','athens-law-courts'].map(x=>quizFingerprint(lessons.find(y=>y.id===x).questions))])assert.equal(lessonQuizMatches(l,old),false);
const attempt={checkpointAnswers:{0:l.questions[0].correctIndex},quizKey:k,score:1,updatedAt:Date.now(),replayOfCompletedLesson:false};
const backup=parseLearningBackup({schemaVersion:1,completedIds:['greek-stage-tragedy','athens-who-voted'],savedIds:[id,'antikythera-gears'],attempts:{[id]:attempt}});
assert.equal(backup.attempts[id].quizKey,k);assert.ok(backup.completedIds.includes('athens-who-voted')&&backup.savedIds.includes(id));
const stale=parseLearningBackup({schemaVersion:1,completedIds:['greek-stage-tragedy'],savedIds:[id],attempts:{[id]:{...attempt,quizKey:'q_obsolete'}}});
assert.ok(!stale.attempts[id]&&stale.savedIds.includes(id));
console.log('Lesson 26 Node-only contract: identity, media, anchors, path, quiz isolation and backups passed.');
