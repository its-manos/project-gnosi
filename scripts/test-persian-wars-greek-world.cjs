require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts'),{inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const progress=require(root+'/src/utils/lessonProgress.ts'),paths=require(root+'/src/utils/lessonPath.ts');
const {quizFingerprint,lessonQuizMatches}=require(root+'/src/utils/learningActivity.ts'),{parseLearningBackup}=require(root+'/src/utils/learningBackup.ts'),{lessonReview}=require(root+'/src/utils/lessonReview.ts');
const id='persian-wars-greek-world',l=lessons.find(x=>x.id===id);
assert.ok(l,'Lesson 19 must exist exactly once');
assert.equal(lessons.filter(x=>x.id===id).length,1);
assert.equal(l.title,'Περσικοί Πόλεμοι: αυτοκρατορία, πόλεις και επιλογές');
assert.equal(l.categoryId,'history');assert.equal(l.subcategoryId,'ancient-greece');
assert.equal(l.requireCurrentAttemptQuiz,true);assert.equal(l.compatibleQuizKeys,undefined);
assert.equal(l.sections.length,6);
const ps=l.sections.flatMap(s=>s.paragraphs);
assert.equal(ps.length,25);
assert.deepEqual(ps.map(p=>p.id),Array.from({length:25},(_,i)=>'persian-'+String(i+1).padStart(2,'0')));
assert.equal(l.questions.length,6);
assert.deepEqual(l.checkpoints.map(c=>c.questionId),l.questions.map(q=>q.id));
assert.deepEqual(progress.getQuestionPlacements(l).map(p=>p.afterParagraphNumber),[4,8,12,17,21,25]);
assert.equal(progress.getVisibleParagraphLimit(l,{}),4);
assert.equal(progress.getResumeParagraphNumber(l,{0:l.questions[0].correctIndex}),5);
assert.equal(progress.getVisibleParagraphLimit(l,Object.fromEntries(l.questions.map((q,i)=>[i,q.correctIndex]))),25);
assert.ok(l.questions.every(q=>q.version==='1'&&q.answers.length===4&&new Set(q.answers).size===4&&Number.isInteger(q.correctIndex)&&q.correctIndex>=0&&q.correctIndex<4&&q.explanation.length>75));
assert.equal(new Set(l.questions.map(q=>q.id)).size,6);
assert.ok(l.sources.length>=16&&l.sources.every(s=>s.url.startsWith('https://')));
assert.ok(l.imageCredit.includes('CC BY-SA 2.5')&&l.imageCreditUrl.includes('commons.wikimedia.org/wiki/File:'));
const media=inlineArticleMedia[id];
assert.equal(media.length,4);
assert.deepEqual(media.map(m=>m.afterParagraphId),['persian-03','persian-11','persian-16','persian-23']);
assert.ok(media.every(m=>m.resizeMode==='contain'&&m.url.includes('Special:FilePath/')&&m.creditUrl.includes('commons.wikimedia.org/wiki/File:')));
const seq=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.deepEqual(seq.slice(16,21).map(x=>x.id),['greek-war-hoplites','greek-sanctuaries-games',id,'athenian-empire','antikythera-gears']);
assert.equal(seq.filter(x=>x.id===id).length,1);
assert.equal(seq.filter(x=>x.id==='athenian-empire').length,1,'Integrated Lesson 20 must be a single live entry');
assert.equal(paths.getLessonAccess(l,lessons,[]).unlocked,false);
assert.equal(paths.getLessonAccess(l,lessons,['greek-sanctuaries-games']).unlocked,true);
assert.equal(paths.getLessonAccess(l,lessons,[id]).unlocked,true);
assert.equal(paths.getNextPathLesson(lessons.find(x=>x.id==='greek-sanctuaries-games'),lessons,['greek-sanctuaries-games'])?.id,id);
