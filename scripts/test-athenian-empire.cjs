/* Lesson 20 — Node-only structural, editorial and immutable-history checks. Native QA is separate. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts'),{inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const progress=require(root+'/src/utils/lessonProgress.ts'),paths=require(root+'/src/utils/lessonPath.ts');
const {quizFingerprint,lessonQuizMatches}=require(root+'/src/utils/learningActivity.ts');
const {parseLearningBackup}=require(root+'/src/utils/learningBackup.ts'),{lessonReview}=require(root+'/src/utils/lessonReview.ts');
const id='athenian-empire',l=lessons.find(x=>x.id===id);
assert.ok(l,'Lesson 20 must be published exactly once');
assert.equal(lessons.filter(x=>x.id===id).length,1);
assert.equal(l.title,'Από τη Δήλο στην αθηναϊκή ηγεμονία');
assert.equal(l.categoryId,'history');assert.equal(l.subcategoryId,'ancient-greece');
assert.equal(l.requireCurrentAttemptQuiz,true);assert.equal(l.compatibleQuizKeys,undefined);
assert.equal(l.sections.length,6);
const ps=l.sections.flatMap(s=>s.paragraphs);
assert.equal(ps.length,26);
assert.deepEqual(ps.map(p=>p.id),Array.from({length:26},(_,i)=>'empire-'+String(i+1).padStart(2,'0')));
assert.equal(l.questions.length,6);
assert.equal(new Set(l.questions.map(q=>q.id)).size,6);
assert.deepEqual(l.checkpoints.map(c=>c.questionId),l.questions.map(q=>q.id));
assert.deepEqual(progress.getQuestionPlacements(l).map(p=>p.afterParagraphNumber),[4,8,13,18,22,26]);
assert.equal(progress.getVisibleParagraphLimit(l,{}),4);
assert.equal(progress.getResumeParagraphNumber(l,{0:l.questions[0].correctIndex}),5);
assert.equal(progress.getVisibleParagraphLimit(l,Object.fromEntries(l.questions.map((q,i)=>[i,q.correctIndex]))),26);
assert.ok(l.questions.every(q=>q.version==='1'&&q.answers.length===4&&new Set(q.answers).size===4&&Number.isInteger(q.correctIndex)&&q.correctIndex>=0&&q.correctIndex<4&&q.explanation.length>70));
assert.ok(l.sources.length>=12&&l.sources.every(s=>s.url.startsWith('https://')));
assert.ok(l.imageCredit.includes('CC BY-SA 3.0')&&l.imageCreditUrl.includes('commons.wikimedia.org/wiki/File:'));
const media=inlineArticleMedia[id];assert.equal(media.length,2);
assert.deepEqual(media.map(m=>m.afterParagraphId),['empire-04','empire-16']);
assert.ok(media.every(m=>m.resizeMode==='contain'&&m.url.includes('Special:FilePath/')&&m.creditUrl.includes('commons.wikimedia.org/wiki/File:')));
const seq=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.deepEqual(seq.slice(17,23).map(x=>x.id),['greek-sanctuaries-games','persian-wars-greek-world',id,'peloponnesian-war','greek-crises-fourth-century','antikythera-gears']);
assert.equal(seq.filter(x=>x.id===id).length,1);
assert.equal(seq.filter(x=>x.id==='peloponnesian-war').length,1,'Lesson 21 is now a single live entry');
assert.equal(paths.getLessonAccess(l,lessons,[]).unlocked,false);
assert.equal(paths.getLessonAccess(l,lessons,['persian-wars-greek-world']).unlocked,true);
assert.equal(paths.getLessonAccess(l,lessons,[id]).unlocked,true);
assert.equal(paths.getNextPathLesson(lessons.find(x=>x.id==='persian-wars-greek-world'),lessons,['persian-wars-greek-world'])?.id,id);
const key=quizFingerprint(l.questions);assert.ok(key.startsWith('q_'));
for(const old of ['q_470dac57','q_22487292',...['athens-law-courts','greek-war-hoplites','greek-sanctuaries-games','persian-wars-greek-world'].map(id=>quizFingerprint(lessons.find(x=>x.id===id).questions))])assert.ok(!lessonQuizMatches(l,old));
const historical={prior:{lessonId:'athens-who-voted',at:Date.parse('2026-10-20T12:00Z'),wasCompleted:true,questionCount:4,correctCount:3,quizKey:'q_470dac57',missedQuestionIndices:[1]}};
assert.equal(lessonReview(l,historical).status,'no-result');
assert.equal(lessonReview(lessons.find(x=>x.id==='athens-who-voted'),historical).status,'changed');
const attempt={checkpointAnswers:{0:l.questions[0].correctIndex},quizKey:key,score:1,updatedAt:Date.now(),replayOfCompletedLesson:false};
const backup=parseLearningBackup({schemaVersion:1,completedIds:['persian-wars-greek-world','athens-who-voted'],savedIds:['athens-who-voted',id],attempts:{[id]:attempt}});
assert.equal(backup.attempts[id].quizKey,key);
assert.ok(backup.completedIds.includes('athens-who-voted')&&backup.savedIds.includes('athens-who-voted'));
const wrong=parseLearningBackup({schemaVersion:1,completedIds:['persian-wars-greek-world'],savedIds:[id],attempts:{[id]:{...attempt,quizKey:'q_wrong'}}});
assert.ok(!wrong.attempts[id]&&wrong.savedIds.includes(id));
console.log('Athenian Empire Lesson 20 structure, images, checkpoints, path and old-history isolation passed (Node only).');
