/* Node-only editorial checks; remote media and physical devices are separate QA. */
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts');
const progress=require(root+'/src/utils/lessonProgress.ts');
const pathing=require(root+'/src/utils/lessonPath.ts');
const {inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const lesson=lessons.find(l=>l.id==='aegean-bronze-age');
assert.ok(lesson&&lesson.requireCurrentAttemptQuiz);
const paragraphs=lesson.sections.flatMap(s=>s.paragraphs);
assert.equal(paragraphs.length,19);
assert.equal(new Set(paragraphs.map(p=>p.id)).size,19);
assert.deepEqual(progress.getQuestionPlacements(lesson).map(x=>x.afterParagraphNumber),[5,10,15,18]);
assert.deepEqual(lesson.checkpoints.map(c=>c.questionId),lesson.questions.map(q=>q.id));
assert.deepEqual(inlineArticleMedia[lesson.id].map(x=>x.afterParagraphId),['spindle-evidence','lerna-seals']);
assert.ok(lesson.questions.every(q=>q.id&&q.version==='1'&&q.answers.length===4&&q.correctIndex>=0&&q.correctIndex<4&&q.explanation.length>35));
const [a,b,c,d]=lesson.questions.map(q=>q.correctIndex);
assert.equal(progress.getVisibleParagraphLimit(lesson,{}),5);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a}),10);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a,1:b}),15);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a,1:b,2:c}),18);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a,1:b,2:c,3:d}),19);
assert.equal(progress.getResumeParagraphNumber(lesson,{0:a}),6);
const ancient=pathing.getSubcategoryPath(lessons,'ancient-greece');
assert.equal(ancient.findIndex(l=>l.id===lesson.id),5);
assert.equal(pathing.getLessonAccess(lesson,lessons,[]).unlocked,false);
assert.equal(pathing.getLessonAccess(lesson,lessons,['greek-geography-seas']).unlocked,true);
assert.equal(pathing.getLessonAccess(lesson,lessons,[lesson.id]).unlocked,true);
assert.equal(pathing.getLessonAccess(lesson,lessons,[],[lesson.id]).unlocked,true);
console.log('Aegean Bronze Age content anchors and progress-policy checks passed (Node only).');
