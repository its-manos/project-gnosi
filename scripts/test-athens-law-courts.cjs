/* Lesson 16 — standalone Node-only invariants; native UI, Supabase and remote images are NOT tested here. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts');
const {inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const progress=require(root+'/src/utils/lessonProgress.ts');
const paths=require(root+'/src/utils/lessonPath.ts');
const {quizFingerprint,lessonQuizMatches}=require(root+'/src/utils/learningActivity.ts');
const {parseLearningBackup}=require(root+'/src/utils/learningBackup.ts');
const {lessonReview}=require(root+'/src/utils/lessonReview.ts');
const old=require('./fixtures/quiz-before-editorial-20261030.json').find(x=>x.id==='athens-who-voted');
const l=lessons.find(x=>x.id==='athens-law-courts');
assert.ok(l,'new lesson must be in catalogue');
assert.equal(lessons.filter(x=>x.id===l.id).length,1,'lesson cannot be published twice');
assert.equal(l.title,'Αθήνα: από την καταγγελία στην ψήφο');
assert.ok(l.requireCurrentAttemptQuiz);
assert.equal(l.sections.length,6);
const paras=l.sections.flatMap(x=>x.paragraphs);
assert.equal(paras.length,28);
assert.deepEqual(paras.map(x=>x.id),Array.from({length:28},(_,i)=>'courts-'+String(i+1).padStart(2,'0')));
assert.equal(l.questions.length,6);
assert.deepEqual(l.checkpoints.map(x=>x.questionId),l.questions.map(x=>x.id));
assert.deepEqual(progress.getQuestionPlacements(l).map(x=>x.afterParagraphNumber),[4,10,15,20,24,28]);
assert.equal(progress.getVisibleParagraphLimit(l,{}),4);
assert.equal(progress.getVisibleParagraphLimit(l,{0:1}),10);
assert.equal(progress.getResumeParagraphNumber(l,{0:1}),5);
assert.equal(progress.getVisibleParagraphLimit(l,{0:1,1:2,2:3,3:2,4:1,5:2}),28);
assert.ok(l.questions.every(q=>q.version==='1'&&q.answers.length===4&&new Set(q.answers).size===4&&q.explanation.length>90));
assert.equal(new Set(l.questions.map(q=>q.id)).size,6);
assert.ok(l.sources.length>=10&&l.sources.every(s=>s.url.startsWith('https://')));
assert.ok(l.imageCredit.includes('CC BY-SA 4.0')&&l.imageCreditUrl.includes('Bronze_pinakia'));
const media=inlineArticleMedia[l.id];
assert.equal(media.length,2);
assert.deepEqual(media.map(m=>m.afterParagraphId),['courts-14','courts-21']);
assert.ok(media.every(m=>m.resizeMode==='contain'&&m.url.startsWith('https://commons.wikimedia.org/wiki/Special:FilePath/')&&m.creditUrl.includes('commons.wikimedia.org/wiki/File:')));
const seq=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.deepEqual(seq.slice(14,17).map(x=>x.id),['athens-who-voted','athens-law-courts','antikythera-gears']);
assert.equal(paths.getLessonAccess(l,lessons,[]).unlocked,false);
assert.equal(paths.getLessonAccess(l,lessons,['athens-who-voted']).unlocked,true);
assert.equal(paths.getLessonAccess(l,lessons,[l.id]).unlocked,true);
const key=quizFingerprint(l.questions);
assert.ok(key.startsWith('q_'));
assert.ok(!lessonQuizMatches(l,'q_470dac57')&&!lessonQuizMatches(l,'q_22487292'),'Lesson 15 keys cannot validate lesson 16');
const attempted={checkpointAnswers:{0:l.questions[0].correctIndex},quizKey:key,score:1,updatedAt:Date.now(),replayOfCompletedLesson:false};
let backup=parseLearningBackup({schemaVersion:1,completedIds:[],savedIds:[l.id],attempts:{[l.id]:attempted}});
assert.equal(backup.attempts[l.id].quizKey,key);
backup=parseLearningBackup({schemaVersion:1,completedIds:[],savedIds:[l.id],attempts:{[l.id]:{...attempted,quizKey:'q_other'}}});
assert.ok(!backup.attempts[l.id]&&backup.savedIds.includes(l.id));
const oldKey=quizFingerprint(old.questions);
assert.equal(oldKey,'q_470dac57');
const oldActivity={prior:{lessonId:'athens-who-voted',at:Date.parse('2026-10-20T12:00Z'),wasCompleted:true,questionCount:4,correctCount:3,quizKey:oldKey,missedQuestionIndices:[1]}};
assert.equal(lessonReview(lessons.find(x=>x.id==='athens-who-voted'),oldActivity).status,'changed');
assert.equal(lessonReview(l,oldActivity).status,'none');
backup=parseLearningBackup({schemaVersion:1,completedIds:['athens-who-voted'],savedIds:['athens-who-voted',l.id],attempts:{'athens-who-voted':{...attempted,quizKey:oldKey}}});
assert.ok(backup.completedIds.includes('athens-who-voted')&&backup.savedIds.includes('athens-who-voted'));
console.log('Lesson 16 legal content, checkpoints, media, path and Lesson 15 historical quiz isolation passed (Node only).');
