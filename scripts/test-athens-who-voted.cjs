/* Lesson 15 live-draft rewrite: structural, source/media, access, version and historical activity safety. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts'),{inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const progress=require(root+'/src/utils/lessonProgress.ts'),paths=require(root+'/src/utils/lessonPath.ts');
const {quizFingerprint,lessonQuizMatches}=require(root+'/src/utils/learningActivity.ts');
const {parseLearningBackup}=require(root+'/src/utils/learningBackup.ts');
const {lessonReview}=require(root+'/src/utils/lessonReview.ts');
const old=require('./fixtures/quiz-before-editorial-20261030.json').find(x=>x.id==='athens-who-voted');
const l=lessons.find(x=>x.id==='athens-who-voted');
assert.ok(l&&old);assert.equal(lessons.filter(x=>x.id===l.id).length,1);assert.equal(l.requireCurrentAttemptQuiz,true);
assert.ok(!l.compatibleQuizKeys?.length,'do not attach old quiz aliases to changed meanings');
assert.equal(l.sections.length,6);
const paras=l.sections.flatMap(x=>x.paragraphs);assert.equal(paras.length,25);
assert.deepEqual(paras.map(x=>x.id),Array.from({length:25},(_,i)=>'athens-'+String(i+1).padStart(2,'0')));
assert.equal(l.questions.length,6);
assert.deepEqual(l.checkpoints.map(x=>x.questionId),l.questions.map(x=>x.id));
assert.deepEqual(progress.getQuestionPlacements(l).map(x=>x.afterParagraphNumber),[4,9,13,17,21,25]);
assert.equal(progress.getVisibleParagraphLimit(l,{}),4);
assert.equal(progress.getResumeParagraphNumber(l,{0:l.questions[0].correctIndex}),5);
assert.ok(l.questions.every(q=>q.version==='1'&&q.answers.length===4&&new Set(q.answers).size===4&&q.explanation.length>=65));
assert.equal(new Set(l.questions.map(q=>q.id)).size,6);
assert.ok(l.sources.length>=11&&l.sources.every(s=>s.url.startsWith('https://')));
assert.ok(l.imageCredit.includes('CC BY-SA 4.0')&&l.imageCreditUrl.includes('Pnyx_and_Bema.jpg'));
const imgs=inlineArticleMedia[l.id];assert.equal(imgs.length,2);
assert.deepEqual(imgs.map(x=>x.afterParagraphId),['athens-07','athens-23']);
assert.ok(imgs.every(x=>x.resizeMode==='contain'&&x.url.startsWith('https://commons.wikimedia.org/wiki/Special:FilePath/')&&x.creditUrl.includes('commons.wikimedia.org/wiki/File:')));
const seq=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.deepEqual(seq.slice(12,15).map(x=>x.id),['greek-settlements-networks','sparta-society','athens-who-voted']);
assert.equal(paths.getLessonAccess(l,lessons,[]).unlocked,false);
assert.equal(paths.getLessonAccess(l,lessons,['sparta-society']).unlocked,true);
assert.equal(paths.getLessonAccess(l,lessons,[l.id]).unlocked,true);
const oldKey=quizFingerprint(old.questions),currentKey=quizFingerprint(l.questions);
assert.notEqual(oldKey,currentKey);assert.ok(!lessonQuizMatches(l,oldKey));
assert.equal(lessonReview(l,{old:{lessonId:l.id,at:Date.parse('2026-10-20T12:00Z'),wasCompleted:false,questionCount:4,correctCount:3,quizKey:oldKey,missedQuestionIndices:[1]}}).status,'changed');
const past={checkpointAnswers:{0:old.questions[0].correctIndex},quizKey:oldKey,score:1,updatedAt:Date.now(),replayOfCompletedLesson:false};
let backup=parseLearningBackup({schemaVersion:1,completedIds:[],savedIds:[l.id],attempts:{[l.id]:past}});
assert.deepEqual(backup.savedIds,[l.id]);assert.ok(!backup.attempts[l.id],'legacy attempt questions may not be reinterpreted');
backup=parseLearningBackup({schemaVersion:1,completedIds:[l.id],savedIds:[l.id],attempts:{[l.id]:past}});
assert.deepEqual(backup.completedIds,[l.id]);assert.deepEqual(backup.savedIds,[l.id]);
backup=parseLearningBackup({schemaVersion:1,completedIds:[],savedIds:[l.id],attempts:{[l.id]:{...past,quizKey:currentKey,checkpointAnswers:{0:l.questions[0].correctIndex}}}});
assert.equal(backup.attempts[l.id].quizKey,currentKey);
console.log('Lesson 15 citizenship content, anchors, media, access and historical quiz separation passed (Node only).');
