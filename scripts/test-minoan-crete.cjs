/* Node-only structural and lesson-progress QA. Device and HTTP testing remain separate. */
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..'),{lessons}=require(root+'/src/data/lessons.ts');
const progress=require(root+'/src/utils/lessonProgress.ts'),pathing=require(root+'/src/utils/lessonPath.ts');
const {inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const lesson=lessons.find(l=>l.id==='minoan-crete');
assert.ok(lesson&&lesson.requireCurrentAttemptQuiz);
const paragraphs=lesson.sections.flatMap(s=>s.paragraphs);
assert.equal(paragraphs.length,22);
assert.equal(new Set(paragraphs.map(p=>p.id)).size,22);
assert.deepEqual(progress.getQuestionPlacements(lesson).map(x=>x.afterParagraphNumber),[4,10,15,20]);
assert.deepEqual(lesson.checkpoints.map(c=>c.questionId),lesson.questions.map(q=>q.id));
assert.deepEqual(inlineArticleMedia[lesson.id].map(x=>x.afterParagraphId),['mu-district','gournia-streets']);
assert.deepEqual(lesson.questions.map(q=>q.correctIndex),[2,0,3,1]);
assert.ok(lesson.questions.every(q=>q.id&&q.version==='1'&&q.answers.length===4&&new Set(q.answers).size===4&&q.explanation.length>35));
const [a,b,c,d]=lesson.questions.map(q=>q.correctIndex);
assert.equal(progress.getVisibleParagraphLimit(lesson,{}),4);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a}),10);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a,1:b}),15);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a,1:b,2:c}),20);
assert.equal(progress.getVisibleParagraphLimit(lesson,{0:a,1:b,2:c,3:d}),22);
assert.equal(progress.getResumeParagraphNumber(lesson,{0:a}),5);
const ordered=pathing.getSubcategoryPath(lessons,'ancient-greece');
assert.equal(ordered.findIndex(l=>l.id===lesson.id),6);
assert.equal(pathing.getLessonAccess(lesson,lessons,[]).unlocked,false);
assert.equal(pathing.getLessonAccess(lesson,lessons,['aegean-bronze-age']).unlocked,true);
assert.equal(pathing.getLessonAccess(lesson,lessons,[lesson.id]).unlocked,true);
assert.equal(pathing.getLessonAccess(lesson,lessons,[],[lesson.id]).unlocked,true);
console.log('Minoan Crete lesson: IDs, questions, anchored media, ordering and progress-policy checks passed (Node only).');
