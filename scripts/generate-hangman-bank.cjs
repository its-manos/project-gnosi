const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const normalize = text => text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase();
const legacy = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures/hangman-before-expansion.json'), 'utf8'));
const ids = new Set(legacy.map(word => word.id));
const words = new Set(legacy.map(word => normalize(word.word)));
const entries = fs.readFileSync(path.join(root, 'content/hangman/words-v2.psv'), 'utf8')
  .split(/\r?\n/).filter(line => line && !line.startsWith('#')).map((line, index) => {
    const fields = line.split('|');
    assert.equal(fields.length, 6, `Row ${index + 1}: expected six fields`);
    const [category, slug, word, difficulty, clue, fact] = fields;
    const id = `hangman-v2-${slug}`;
    assert.match(slug, /^[a-z]+(?:-[a-z]+)*$/, id);
    assert.ok(!ids.has(id) && !words.has(normalize(word)), `Duplicate: ${id}`);
    assert.match(normalize(word), /^[Α-ΡΣ-Ω]{4,13}$/u, id);
    assert.ok(['easy', 'medium', 'hard'].includes(difficulty), id);
    assert.ok(clue.length > 15 && fact.length > 15, id);
    assert.ok(!normalize(clue).includes(normalize(word)), `Clue reveals ${id}`);
    ids.add(id); words.add(normalize(word));
    return { id, word, category, difficulty, clue, fact };
  });
assert.equal(entries.length, 152);
const categories = new Set([...legacy, ...entries].map(word => word.category));
assert.equal(categories.size, 9);
for (const category of categories) {
  const added = entries.filter(word => word.category === category);
  assert.equal([...legacy, ...added].filter(word => word.category === category).length, 20, category);
  const expected = legacy.some(word => word.category === category) ? [6, 7, 3] : [8, 8, 4];
  assert.deepEqual(['easy', 'medium', 'hard'].map(level => added.filter(word => word.difficulty === level).length), expected, category);
}
const target = path.join(root, 'src/games/hangman/extraWords.ts');
const output = '// Generated by scripts/generate-hangman-bank.cjs. Edit content/hangman/words-v2.psv.\n' +
  'import type { HangmanWord } from "./words";\n\n' +
  'export const extraHangmanWords: readonly HangmanWord[] = ' + JSON.stringify(entries, null, 2) + ';\n';
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), output, 'Run node scripts/generate-hangman-bank.cjs');
else fs.writeFileSync(target, output);
console.log(`Hangman bank: ${entries.length} additions validated; 180 words across nine categories.`);
