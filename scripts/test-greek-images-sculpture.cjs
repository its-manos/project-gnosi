/* Ancient Greece / Lesson 27: Node-only contract; not device or editorial sign-off. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const root=path.resolve(__dirname,'..');
const {lessons}=require(root+'/src/data/lessons.ts');
const {inlineArticleMedia}=require(root+'/src/data/articleMedia.ts');
const progress=require(root+'/src/utils/lessonProgress.ts');
const paths=require(root+'/src/utils/lessonPath.ts');
const {quizFingerprint,lessonQuizMatches}=require(root+'/src/utils/learningActivity.ts');
const {parseLearningBackup,mergeLearningBackups}=require(root+'/src/utils/learningBackup.ts');
const id='greek-images-sculpture',l=lessons.find(x=>x.id===id);
assert.ok(l,'Lesson 27 is registered');
assert.equal(lessons.filter(x=>x.id===id).length,1);
assert.equal(l.categoryId,'history');assert.equal(l.subcategoryId,'ancient-greece');
assert.equal(l.title,'Τι έβλεπαν μπροστά σε ένα αρχαίο άγαλμα;');
assert.equal(l.requireCurrentAttemptQuiz,true);assert.equal(l.compatibleQuizKeys,undefined);
const ps=l.sections.flatMap(s=>s.paragraphs);
assert.equal(l.sections.length,6);assert.equal(ps.length,28);
assert.deepEqual(ps.map(p=>p.id),Array.from({length:28},(_,i)=>'images-'+String(i+1).padStart(2,'0')));
assert.ok(ps.every(p=>p.text.length>=140));
assert.equal(l.questions.length,6);assert.equal(new Set(l.questions.map(q=>q.id)).size,6);
assert.ok(l.questions.every(q=>q.id.startsWith('images-')&&q.version==='1'&&q.difficulty==='hard'&&q.conceptIds.length===2&&q.answers.length===4&&new Set(q.answers).size===4&&q.correctIndex>=0&&q.correctIndex<4&&q.explanation.length>=100));
assert.deepEqual(l.checkpoints.map(c=>c.questionId),l.questions.map(q=>q.id));
assert.deepEqual(l.checkpoints.map(c=>c.afterParagraphId),['images-05','images-10','images-14','images-19','images-24','images-28']);
assert.deepEqual(progress.getQuestionPlacements(l).map(q=>q.afterParagraphNumber),[5,10,14,19,24,28]);
assert.equal(progress.getVisibleParagraphLimit(l,{}),5);
assert.equal(progress.getResumeParagraphNumber(l,{0:l.questions[0].correctIndex}),6);
assert.equal(progress.getVisibleParagraphLimit(l,Object.fromEntries(l.questions.map((q,i)=>[i,q.correctIndex]))),28);
assert.ok(l.sources.length>=10&&l.sources.every(s=>s.url.startsWith('https://')));
assert.ok(l.imageUrl.includes('commons.wikimedia.org/wiki/Special:FilePath/')&&l.imageCreditUrl.includes('commons.wikimedia.org/wiki/File:'));
assert.equal(l.imageResizeMode,'contain');
assert.equal(inlineArticleMedia[id].length,2);
assert.deepEqual(inlineArticleMedia[id].map(x=>x.afterParagraphId),['images-13','images-18']);
assert.ok(inlineArticleMedia[id].every(x=>x.resizeMode==='contain'&&x.creditUrl.includes('/wiki/File:')&&x.caption.length>=130));
const seq=paths.getSubcategoryPath(lessons,'ancient-greece');
assert.equal(seq.length,30);
assert.deepEqual(seq.slice(24).map(x=>x.id),['hellenistic-kingdoms-cities', 'greek-stage-tragedy', 'greek-images-sculpture', 'greek-philosophy-in-context', 'greek-science-knowledge', 'antikythera-gears']);
assert.equal(paths.getNextPathLesson(lessons.find(x=>x.id==='greek-stage-tragedy'),lessons,['greek-stage-tragedy'])?.id,id);
assert.equal(paths.getNextPathLesson(l,lessons,[id])?.id,'greek-philosophy-in-context');
assert.ok(paths.getLessonAccess(l,lessons,['greek-stage-tragedy']).unlocked);
assert.ok(!paths.getLessonAccess(l,lessons,['greek-philosophy-in-context']).unlocked);
assert.ok(paths.getLessonAccess(l,lessons,[id]).unlocked);
const key=quizFingerprint(l.questions);
assert.ok(/^q_[a-f0-9]+$/.test(key));
for(const old of ['q_470dac57','q_22487292',...['greek-science-knowledge','greek-philosophy-in-context','greek-stage-tragedy','antikythera-gears','athens-who-voted'].map(pid=>quizFingerprint(lessons.find(x=>x.id===pid).questions))])assert.equal(lessonQuizMatches(l,old),false);
const attempt={checkpointAnswers:{0:l.questions[0].correctIndex},quizKey:key,score:1,updatedAt:Date.now(),replayOfCompletedLesson:false};
const baseline=parseLearningBackup({schemaVersion:1,completedIds:['greek-science-knowledge','athens-who-voted'],savedIds:[id,'antikythera-gears'],attempts:{[id]:attempt}});
assert.ok(baseline.completedIds.includes('athens-who-voted')&&baseline.savedIds.includes(id));
assert.equal(baseline.attempts[id].quizKey,key);
const stale=parseLearningBackup({schemaVersion:1,completedIds:['greek-science-knowledge'],savedIds:[id],attempts:{[id]:{...attempt,quizKey:'q_stale'}}});
assert.ok(!stale.attempts[id]&&stale.savedIds.includes(id));
const merged=mergeLearningBackups(baseline,parseLearningBackup({schemaVersion:1,completedIds:['antikythera-gears'],savedIds:[],attempts:{}}));
assert.ok(merged.completedIds.includes('athens-who-voted')&&merged.completedIds.includes('antikythera-gears'));
assert.ok(merged.savedIds.includes(id)&&merged.attempts[id].quizKey===key);
console.log('Lesson 27 Node-only contract passed: identity, anchors, images, path, fingerprint isolation, backup and merge compatibility.');
